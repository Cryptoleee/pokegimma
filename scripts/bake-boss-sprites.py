#!/usr/bin/env python3
"""
Bake the animated Black/White sprites of the raid bosses (and their other forms)
into PNG sprite sheets plus frame timings, so the canvas can play them.
Needs ffmpeg and Pillow. Output is committed (the Vercel build has no ffmpeg):
  src/assets/boss/<id>.png    frames in a grid, every cell the same size
  src/data/bossAnims.ts       cell size, columns and per-frame durations

Run: python3 scripts/bake-boss-sprites.py
"""
import io, math, os, subprocess, tempfile, urllib.request
from PIL import Image

IDS = [643, 644, 646, 10022, 384, 10079, 150, 10044]
BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/versions/generation-v/black-white/animated'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_FRAMES = 96

def frames_of(gif_bytes):
    """Fully composited RGBA frames (ffmpeg handles GIF disposal) + durations in ms."""
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, 'a.gif')
        open(src, 'wb').write(gif_bytes)
        subprocess.run(['ffmpeg', '-v', 'error', '-i', src, '-vsync', '0', '-pix_fmt', 'rgba', os.path.join(d, 'f%04d.png')], check=True)
        imgs = [Image.open(os.path.join(d, f)).convert('RGBA') for f in sorted(os.listdir(d)) if f.startswith('f')]
    gif = Image.open(io.BytesIO(gif_bytes))
    durs = []
    for i in range(gif.n_frames):
        gif.seek(i)
        durs.append(max(20, gif.info.get('duration', 100) or 100))
    n = min(len(imgs), len(durs))
    return imgs[:n], durs[:n]

out = {}
for id in IDS:
    raw = urllib.request.urlopen(f'{BASE}/{id}.gif').read()
    imgs, durs = frames_of(raw)
    # Merge identical consecutive frames
    fr, du = [imgs[0]], [durs[0]]
    for im, d in zip(imgs[1:], durs[1:]):
        if im.tobytes() == fr[-1].tobytes():
            du[-1] += d
        else:
            fr.append(im); du.append(d)
    # Long loops: keep every other frame
    while len(fr) > MAX_FRAMES:
        fr = fr[::2]
        du = [du[i] + (du[i + 1] if i + 1 < len(du) else 0) for i in range(0, len(du), 2)]
    # One box for all frames, so the sprite doesn't jitter
    box = None
    for im in fr:
        b = im.getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    w, h = box[2] - box[0], box[3] - box[1]
    cols = max(1, min(len(fr), math.ceil(math.sqrt(len(fr) * h / w))))
    rows = math.ceil(len(fr) / cols)
    sheet = Image.new('RGBA', (cols * w, rows * h), (0, 0, 0, 0))
    for i, im in enumerate(fr):
        sheet.paste(im.crop(box), ((i % cols) * w, (i // cols) * h))
    # Hard alpha (pixel art), then a palette PNG to keep it small
    a = sheet.getchannel('A').point(lambda v: 255 if v > 20 else 0)
    sheet.putalpha(a)
    q = sheet.quantize(colors=255, method=Image.Quantize.FASTOCTREE)
    path = os.path.join(ROOT, 'src/assets/boss', f'{id}.png')
    q.save(path, optimize=True)
    out[id] = (w, h, cols, du)
    print(id, len(fr), 'frames', (w, h), 'sheet', sheet.size, os.path.getsize(path) // 1024, 'KB')

lines = ['// Generated by scripts/bake-boss-sprites.py: do not edit.', '',
         '/** Animated boss sprites: cell size, columns in the sheet, and how long each frame shows (ms). */',
         'export const BOSS_ANIMS: Record<number, { w: number; h: number; cols: number; durs: number[] }> = {']
for id, (w, h, cols, du) in out.items():
    lines.append(f'  {id}: {{ w: {w}, h: {h}, cols: {cols}, durs: [{", ".join(map(str, du))}] }},')
lines.append('}')
open(os.path.join(ROOT, 'src/data/bossAnims.ts'), 'w').write('\n'.join(lines) + '\n')
