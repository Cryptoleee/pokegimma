#!/usr/bin/env python3
"""
Turn an AI-animated greenscreen clip of a boss sprite into a pixel-art sprite
sheet that matches the real sprite: chroma key, scale back down to sprite size,
snap every pixel to the original sprite's palette, hard alpha.

  python3 scripts/bake-ai-anim.py <clip.mp4> <species> <action> <scale> <first> <last> [fps] [key]

  scale       how much bigger the sprite was in the start frame of the clip (e.g. 6.3)
  first/last  frame range to keep (after resampling to fps, default 12)
  key         screen colour, default green 0x00b140; use magenta 0xff00ff for green Pokémon

Writes src/assets/boss/<species>-<action>.png and updates src/data/bossActions.ts.
"""
import glob, json, math, os, re, subprocess, sys, tempfile
from PIL import Image

clip, species, action, scale, first, last = sys.argv[1], int(sys.argv[2]), sys.argv[3], float(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6])
fps = int(sys.argv[7]) if len(sys.argv) > 7 else 12
key = sys.argv[8] if len(sys.argv) > 8 else '0x00b140'
keyf = f'chromakey={key}:0.16:0.06' + (',despill=type=green' if key == '0x00b140' else '')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Palette of the real (baked) sprite
src = Image.open(os.path.join(ROOT, 'src/assets/boss', f'{species}.png')).convert('RGBA')
count = {}
for c in src.get_flattened_data() if hasattr(src, 'get_flattened_data') else src.getdata():
    if c[3]: count[c[:3]] = count.get(c[:3], 0) + 1
pal = [c for c, _ in sorted(count.items(), key=lambda kv: -kv[1])][:64]
pimg = Image.new('P', (1, 1))
pimg.putpalette(sum(pal, ()) + (0, 0, 0) * (256 - len(pal)))

with tempfile.TemporaryDirectory() as d:
    subprocess.run(['ffmpeg', '-v', 'error', '-i', clip, '-vf', f'fps={fps},{keyf},format=rgba', os.path.join(d, 'f%04d.png')], check=True)
    files = sorted(glob.glob(os.path.join(d, 'f*.png')))[first:last + 1]
    frames = []
    for f in files:
        im = Image.open(f).convert('RGBA')
        small = im.resize((round(im.width / scale), round(im.height / scale)), Image.BOX)
        alpha = small.getchannel('A').point(lambda v: 255 if v > 140 else 0)
        if key != '0x00b140':
            # The model may tint the magenta screen lilac or even white while something glows:
            # flood in from the edges over light or magenta pixels (the body itself is not reached)
            px, al = small.load(), alpha.load()
            W, H = small.size
            def bg(x, y):
                r, g, b, _ = px[x, y]
                return al[x, y] and ((min(r, g, b) > 150 and max(r, g, b) - min(r, g, b) < 70) or g < min(r, b) - 8)
            todo = [(x, y) for x in range(W) for y in (0, H - 1)] + [(x, y) for y in range(H) for x in (0, W - 1)]
            while todo:
                x, y = todo.pop()
                if 0 <= x < W and 0 <= y < H and bg(x, y):
                    al[x, y] = 0
                    todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
        px = small.convert('RGB').quantize(palette=pimg, dither=Image.Dither.NONE).convert('RGBA')
        px.putalpha(alpha)
        frames.append(px)

box = None
for im in frames:
    b = im.getbbox()
    if b: box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
frames = [im.crop(box) for im in frames]
w, h = frames[0].size
cols = max(1, math.ceil(math.sqrt(len(frames) * h / w)))
rows = math.ceil(len(frames) / cols)
sheet = Image.new('RGBA', (cols * w, rows * h))
for i, im in enumerate(frames):
    sheet.paste(im, ((i % cols) * w, (i // cols) * h))
out = os.path.join(ROOT, 'src/assets/boss', f'{species}-{action}.png')
sheet.quantize(colors=255, method=Image.Quantize.FASTOCTREE).save(out, optimize=True)

# Registry of action animations
reg_path = os.path.join(ROOT, 'src/data/bossActions.ts')
reg = {}
if os.path.exists(reg_path):
    m = re.search(r'= (\{.*\})\n', open(reg_path).read(), re.S)
    if m: reg = json.loads(m.group(1))
reg[f'{species}-{action}'] = {'w': w, 'h': h, 'cols': cols, 'durs': [round(1000 / fps)] * len(frames)}
open(reg_path, 'w').write(
    '// Generated by scripts/bake-ai-anim.py: do not edit.\n\n'
    '/** One-shot action animations (AI-animated, snapped back to pixel art), keyed "<species>-<action>". */\n'
    'export const BOSS_ACTIONS: Record<string, { w: number; h: number; cols: number; durs: number[] }> = '
    + json.dumps(reg) + '\n')
print(out, len(frames), 'frames', (w, h), os.path.getsize(out) // 1024, 'KB')
